import re, json, sys
root = sys.argv[1]
ids = dict((m[0], int(m[1])) for m in re.findall(r'(\w+)\s*=\s*(\d+),', open(root+'/blocks/roli_BlockConfigId.h').read()))
src = open(root+'/blocks/roli_BlockConfigManager.h').read()
body = src[src.index('defaultConfig[numDefaultConfigItems] ='):]
body = body[body.index('{')+1:]
body = body[:body.index('};')]
groups = dict(re.findall(r'(\w+Group) = "([^"]*)"', src))
body = re.sub(r'//[^\n]*', '', body)
items = []
depth=0; cur=''
for ch in body:
    if ch=='{':
        depth+=1
        if depth==1: cur=''; continue
    if ch=='}':
        depth-=1
        if depth==0: items.append(cur); continue
    if depth>=1: cur+=ch
out=[]
lim={'INT32_MIN':-2**31,'INT32_MAX':2**31-1}
for it in items:
    opts = re.search(r'\{([^}]*)\}', it)
    optlist = re.findall(r'"([^"]*)"', opts.group(1)) if opts else []
    flat = re.sub(r'\{[^}]*\}', '{}', it)
    parts=[p.strip() for p in flat.split(',')]
    name = parts[5].strip('"') if parts[5].startswith('"') else None
    g = parts[8]
    out.append(dict(id=ids[parts[0]], key=parts[0],
        def_=int(lim.get(parts[1],parts[1])), min=int(lim.get(parts[2],parts[2])), max=int(lim.get(parts[3],parts[3])),
        name=name, type=parts[6].split('::')[1], options=[o.strip() for o in optlist], group=groups.get(g)))
print(len(out), file=sys.stderr)
js = json.dumps(out, indent=1).replace('"def_"','"default"')
print("// Generated by tools/gen-config-items.py from ROLI's roli_blocks_basics (ISC licence).\n// Default values, ranges and names as ROLI's own host code describes them.\n(function (root) {\n  var CONFIG_ITEMS = " + js + ";\n  if (typeof module !== 'undefined') module.exports = CONFIG_ITEMS; else root.CONFIG_ITEMS = CONFIG_ITEMS;\n})(this);")
